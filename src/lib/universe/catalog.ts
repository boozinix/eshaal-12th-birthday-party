export function buildUniverse(): UniverseObject[] {
  return CATALOG.map((e) => {
    const dist = e.d ?? (e.z !== undefined ? comovingDistance(e.z) : 0);
    if (e.atOrigin) return { ...e, dist, pos: [0, 0, 0], radius: dist };
    const radius = e.r ?? (e.size ? Math.max(...e.size) : 0.01);
    return { ...e, dist, pos: raDecToXYZ(e.ra, e.dec, dist), radius };
  });
}
