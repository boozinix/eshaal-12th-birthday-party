import { comovingDistance, raDecToXYZ } from "./cosmology";

export type ObjectType =
  | "galaxy"
  | "group"
  | "cluster"
  | "supercluster"
  | "void"
  | "wall"
  | "quasar"
  | "landmark";

export type Shape = "point" | "sphere" | "ellipsoid" | "shell" | "ring";

export interface CatalogEntry {
  id: string;
  name: string;
  alt?: string;
  type: ObjectType;
  /** Right ascension, degrees (J2000). */
  ra: number;
  /** Declination, degrees (J2000). */
  dec: number;
  /** Comoving distance in Mpc. Give either `d` or `z`. */
  d?: number;
  /** Redshift (converted to comoving distance with flat ΛCDM, H0 = 70). */
  z?: number;
  /** Characteristic radius in Mpc (sphere/shell) or semi-axes [along RA, along Dec, along line of sight]. */
  r?: number;
  size?: [number, number, number];
  shape?: Shape;
  /** Position or size is a rough estimate. */
  approx?: boolean;
  /** Shell centred on the Milky Way whose radius is its distance (horizons). */
  atOrigin?: boolean;
  desc: string;
}

export interface UniverseObject extends CatalogEntry {
  dist: number;
  pos: [number, number, number];
  radius: number;
}

